# ==================== Multi-Dataset Factory ====================

def build_multi_dataset(
    data_dirs: List[str],
    max_samples: Optional[int] = None,
    **kwargs,
) -> "torch.utils.data.ConcatDataset":
    """
    Build a ConcatDataset from multiple data directories.

    Each entry in *data_dirs* is a string ``"path:label"`` where *label*
    is the design-space name (topopt, finray, graph, lattice).
    If the ``:label`` part is omitted the label is inferred from the
    directory name (last component of the path).

    Example::

        ds = build_multi_dataset([
            "data/mechanism_dataset:topopt",
            "data/finray_dataset:finray",
        ])

    Args:
        data_dirs: List of ``"path"`` or ``"path:label"`` strings.
        max_samples: Per-directory sample cap (None = all).
        **kwargs: Forwarded to MechanismConditionedDataset.

    Returns:
        A ``ConcatDataset`` merging all sub-datasets.
    """
    from torch.utils.data import ConcatDataset

    sub_datasets = []
    for entry in data_dirs:
        if ":" in entry:
            path, label = entry.rsplit(":", 1)
        else:
            path = entry
            label = Path(path).name.split("_")[0]  # e.g. "finray" from "finray_dataset"

        ds = MechanismConditionedDataset(
            data_dir=path,
            max_samples=max_samples,
            design_space_override=label,
            **kwargs,
        )
        sub_datasets.append(ds)

    combined = ConcatDataset(sub_datasets)
    total = sum(len(d) for d in sub_datasets)
    print(f"[MultiDataset] {len(sub_datasets)} sources, {total} samples total")
    return combined
    
