"""
Mechanism Dataset Loader

Data loading utilities for mechanism topology optimization dataset.
Loads npz files generated by generate_mechanism_dataset.py for CFM training.

Dataset format (per sample):
    - geometry: (ny, nx) binary structure, 1=solid, 0=void
    - BCx, BCy: (ny, nx) fixed boundary conditions
    - inputx, inputy: (ny, nx) input forces/displacements
    - outputx, outputy: (ny, nx) objective directions (-1=max, 1=min)
    - objective_value: scalar optimization result
    - volume_fraction: scalar target volume fraction
"""

import torch
from torch.utils.data import Dataset, DataLoader
from pathlib import Path
import numpy as np
from typing import Optional, Tuple, List, Dict, Union
from einops import rearrange


# ==================== Utility Functions ====================

def image_to_flat(tensor: torch.Tensor) -> torch.Tensor:
    """
    Flatten spatial dimensions: (B, C, H, W) -> (B, H*W, C)
    """
    return rearrange(tensor, 'b c h w -> b (h w) c')


def flat_to_image(tensor: torch.Tensor, height: int, width: int) -> torch.Tensor:
    """
    Unflatten spatial dimensions: (B, H*W, C) -> (B, C, H, W)
    """
    return rearrange(tensor, 'b (h w) c -> b c h w', h=height, w=width)


def cycle(dataloader):
    """Infinite iterator over dataloader."""
    while True:
        for batch in dataloader:
            yield batch


# ==================== Main Dataset Class ====================

class MechanismDataset(Dataset):
    """
    PyTorch Dataset for mechanism topology optimization data.
    
    Loads npz files containing:
        - geometry: Binary structure (ny, nx)
        - Boundary conditions: BCx, BCy, inputx, inputy, outputx, outputy
        - Scalars: objective_value, volume_fraction
    
    Output tensor format:
        - If return_img=True: (C, H, W) where C depends on channels config
        - If return_img=False: (H*W, C) flattened
    
    Channel configuration (default 7 channels):
        0: geometry (structure)
        1: BCx (fixed x)
        2: BCy (fixed y)
        3: inputx (force/disp x)
        4: inputy (force/disp y)
        5: outputx (objective x)
        6: outputy (objective y)
    """
    
    # Default channel names in order
    CHANNEL_NAMES = [
        'geometry', 'BCx', 'BCy', 'inputx', 'inputy', 'outputx', 'outputy'
    ]
    
    def __init__(
        self,
        data_dir: Union[str, Path],
        channels: Optional[List[str]] = None,
        return_img: bool = True,
        use_double: bool = False,
        normalize_geometry: bool = False,
        include_scalars: bool = False,
        file_pattern: str = "data_*.npz",
        max_samples: Optional[int] = None,
        transform: Optional[callable] = None,
    ):
        """
        Initialize mechanism dataset.
        
        Args:
            data_dir: Path to directory containing npz files
            channels: List of channel names to load. Default: all 7 channels
            return_img: If True, return (C, H, W); else (H*W, C)
            use_double: Use float64 instead of float32
            normalize_geometry: Normalize geometry to [-1, 1] instead of [0, 1]
            include_scalars: Include objective_value and volume_fraction in output
            file_pattern: Glob pattern for npz files
            max_samples: Limit number of samples (for debugging)
            transform: Optional transform to apply to data
        """
        super().__init__()
        
        self.data_dir = Path(data_dir)
        self.channels = channels if channels is not None else self.CHANNEL_NAMES.copy()
        self.return_img = return_img
        self.dtype = torch.float64 if use_double else torch.float32
        self.normalize_geometry = normalize_geometry
        self.include_scalars = include_scalars
        self.transform = transform
        
        # Find all npz files
        self.file_paths = sorted(
            self.data_dir.glob(file_pattern),
            key=lambda p: int(p.stem.split('_')[-1])  # Sort by index
        )
        
        if max_samples is not None:
            self.file_paths = self.file_paths[:max_samples]
        
        if len(self.file_paths) == 0:
            raise FileNotFoundError(f"No npz files found in {self.data_dir}")
        
        # Load first file to get dimensions
        sample = np.load(self.file_paths[0])
        self.height, self.width = sample['geometry'].shape
        self.n_channels = len(self.channels)
        
        print(f"[MechanismDataset] Loaded {len(self.file_paths)} samples from {self.data_dir}")
        print(f"  Shape: ({self.n_channels}, {self.height}, {self.width})")
        print(f"  Channels: {self.channels}")
        print(f"  Dtype: {self.dtype}")
    
    def __len__(self) -> int:
        return len(self.file_paths)
    
    def __getitem__(self, index: int) -> Union[torch.Tensor, Tuple[torch.Tensor, Dict]]:
        if index >= len(self):
            raise IndexError(f"Index {index} out of range for dataset of size {len(self)}")
        
        # Load npz file
        data = np.load(self.file_paths[index])
        
        # Stack selected channels
        arrays = []
        for ch_name in self.channels:
            arr = data[ch_name].astype(np.float32)
            
            # Normalize geometry if requested
            if ch_name == 'geometry' and self.normalize_geometry:
                arr = arr * 2.0 - 1.0  # [0, 1] -> [-1, 1]
            
            arrays.append(arr)
        
        # Stack to (C, H, W)
        tensor = np.stack(arrays, axis=0)
        tensor = torch.tensor(tensor, dtype=self.dtype)
        
        # Flatten if requested
        if not self.return_img:
            tensor = rearrange(tensor, 'c h w -> (h w) c')
        
        # Apply transform if provided
        if self.transform is not None:
            tensor = self.transform(tensor)
        
        # Return with scalars if requested
        if self.include_scalars:
            scalars = {
                'objective_value': float(data['objective_value']),
                'volume_fraction': float(data['volume_fraction']),
                'file_path': str(self.file_paths[index]),
            }
            return tensor, scalars
        
        return tensor
    
    def get_sample_with_metadata(self, index: int) -> Tuple[torch.Tensor, Dict]:
        """Get sample with all metadata."""
        data = np.load(self.file_paths[index])
        
        # Load tensor
        arrays = [data[ch].astype(np.float32) for ch in self.channels]
        tensor = torch.tensor(np.stack(arrays, axis=0), dtype=self.dtype)
        
        if not self.return_img:
            tensor = rearrange(tensor, 'c h w -> (h w) c')
        
        # Load all metadata
        metadata = {
            'objective_value': float(data['objective_value']),
            'volume_fraction': float(data['volume_fraction']),
            'penal': float(data['penal']),
            'rmin': float(data['rmin']),
            'disp_mag': float(data['disp_mag']),
            'file_path': str(self.file_paths[index]),
        }
        
        return tensor, metadata
    
    @property
    def shape(self) -> Tuple[int, int, int]:
        """Return (C, H, W) shape."""
        return (self.n_channels, self.height, self.width)


# ==================== Specialized Dataset Variants ====================

class MechanismConditionedDataset(Dataset):
    """
    Dataset that returns (geometry, condition) pairs for conditional generation.
    
    Geometry: The structure to generate (target)
    Condition: Boundary conditions + scalar metadata defining the problem
    
    Condition channels (10 total):
        0  BCx          Fixed BC mask (x-direction)
        1  BCy          Fixed BC mask (y-direction)
        2  inputx       Prescribed displacement (x)
        3  inputy       Prescribed displacement (y)
        4  outputx      Output DOF indicator (x)
        5  outputy      Output DOF indicator (y)
        6  w_topopt     Design-space blend weight (broadcast across H×W)
        7  w_finray     Design-space blend weight (broadcast across H×W)
        8  w_graph      Design-space blend weight (broadcast across H×W)
        9  w_lattice    Design-space blend weight (broadcast across H×W)
    """

    # Registry: name → channel index (starting from 6)
    DESIGN_SPACES = ['topopt', 'finray', 'graph', 'lattice']
    DS_CHANNEL_OFFSET = 6  # first design-space channel
    N_COND_CHANNELS = 6 + len(DESIGN_SPACES)  # 10
    
    def __init__(
        self,
        data_dir: Union[str, Path],
        return_img: bool = True,
        use_double: bool = False,
        normalize_geometry: bool = True,
        file_pattern: str = "data_*.npz",
        max_samples: Optional[int] = None,
        design_space_override: Optional[str] = None,
    ):
        """
        Initialize conditioned dataset.
        
        Args:
            data_dir: Path to npz files
            return_img: Return image format (C, H, W) vs flat (H*W, C)
            use_double: Use float64
            normalize_geometry: Normalize geometry to [-1, 1]
            file_pattern: File glob pattern
            max_samples: Limit samples for debugging
            design_space_override: If set, use this label for *all* samples
                instead of reading 'design_space' from each npz.  Useful when
                the npz files don't have a design_space field (e.g. finray).
        """
        super().__init__()
        
        self.data_dir = Path(data_dir)
        self.return_img = return_img
        self.dtype = torch.float64 if use_double else torch.float32
        self.normalize_geometry = normalize_geometry
        # Infer design space from directory name if not explicitly set
        if design_space_override is None:
            dir_name = self.data_dir.name.lower()
            for ds in self.DESIGN_SPACES:
                if ds in dir_name:
                    design_space_override = ds
                    break
        self.design_space_override = design_space_override
        
        # Find files
        self.file_paths = sorted(
            self.data_dir.glob(file_pattern),
            key=lambda p: int(p.stem.split('_')[-1])
        )
        
        if max_samples:
            self.file_paths = self.file_paths[:max_samples]
        
        if not self.file_paths:
            raise FileNotFoundError(f"No npz files in {self.data_dir}")
        
        # Get dimensions
        sample = np.load(self.file_paths[0])
        self.height, self.width = sample['geometry'].shape
        
        print(f"[MechanismConditionedDataset] {len(self.file_paths)} samples from {self.data_dir}")
        ds_label = self.design_space_override or 'auto'
        print(f"  Geometry shape: (1, {self.height}, {self.width})  design_space={ds_label}")
        print(f"  Condition shape: ({self.N_COND_CHANNELS}, {self.height}, {self.width})")
        print(f"    ch 0-5: BCs | ch 6-{self.N_COND_CHANNELS-1}: design [{', '.join(self.DESIGN_SPACES)}]")
    
    def __len__(self) -> int:
        return len(self.file_paths)
    
    def __getitem__(self, index: int) -> Tuple[torch.Tensor, torch.Tensor, float]:
        """
        Returns:
            geometry: (1, H, W) or (H*W, 1) - the structure to generate
            condition: (N_COND_CHANNELS, H, W) - BCs + design blend
            vol_frac: scalar float - target volume fraction (metadata only, not used in conditioning)
        """
        data = np.load(self.file_paths[index])
        
        # Geometry (target)
        geom = data['geometry'].astype(np.float32)
        if self.normalize_geometry:
            geom = geom * 2.0 - 1.0
        geom = torch.tensor(geom, dtype=self.dtype).unsqueeze(0)  # (1, H, W)
        
        # Condition: start with 6 BC channels
        bc_channels = ['BCx', 'BCy', 'inputx', 'inputy', 'outputx', 'outputy']
        cond = np.stack([data[ch].astype(np.float32) for ch in bc_channels], axis=0)
        cond = torch.tensor(cond, dtype=self.dtype)  # (6, H, W)

        H, W = cond.shape[1], cond.shape[2]

        # Channels 6-9: design-space blend weights (broadcast across entire spatial map)
        ds_channels = torch.zeros(len(self.DESIGN_SPACES), H, W, dtype=self.dtype)
        if self.design_space_override is not None:
            ds_name = self.design_space_override
        else:
            ds_name = str(data.get('design_space', 'topopt'))
        if ds_name in self.DESIGN_SPACES:
            ds_idx = self.DESIGN_SPACES.index(ds_name)
        else:
            ds_idx = 0  # default to topopt
        ds_channels[ds_idx, :, :] = 1.0

        cond = torch.cat([cond, ds_channels], dim=0)  # (10, H, W)

        # vol_frac kept as scalar metadata (unused by model/physics)
        vol_frac = float(data.get('volume_fraction', 0.3))

        if not self.return_img:
            geom = rearrange(geom, 'c h w -> (h w) c')
            cond = rearrange(cond, 'c h w -> (h w) c')
        
        return geom, cond, vol_frac
    
    @property
    def geometry_shape(self) -> Tuple[int, int, int]:
        return (1, self.height, self.width)
    
    @property
    def condition_shape(self) -> Tuple[int, int, int]:
        return (self.N_COND_CHANNELS, self.height, self.width)


class MechanismGeometryOnlyDataset(Dataset):
    """
    Simple dataset that returns only geometry for unconditional training.
    """
    
    def __init__(
        self,
        data_dir: Union[str, Path],
        return_img: bool = True,
        use_double: bool = False,
        normalize: bool = True,
        file_pattern: str = "data_*.npz",
        max_samples: Optional[int] = None,
    ):
        super().__init__()
        
        self.data_dir = Path(data_dir)
        self.return_img = return_img
        self.dtype = torch.float64 if use_double else torch.float32
        self.normalize = normalize
        
        self.file_paths = sorted(
            self.data_dir.glob(file_pattern),
            key=lambda p: int(p.stem.split('_')[-1])
        )
        
        if max_samples:
            self.file_paths = self.file_paths[:max_samples]
        
        if not self.file_paths:
            raise FileNotFoundError(f"No npz files in {self.data_dir}")
        
        sample = np.load(self.file_paths[0])
        self.height, self.width = sample['geometry'].shape
        
        print(f"[MechanismGeometryOnlyDataset] {len(self.file_paths)} samples, shape=(1, {self.height}, {self.width})")
    
    def __len__(self) -> int:
        return len(self.file_paths)
    
    def __getitem__(self, index: int) -> torch.Tensor:
        data = np.load(self.file_paths[index])
        geom = data['geometry'].astype(np.float32)
        
        if self.normalize:
            geom = geom * 2.0 - 1.0
        
        tensor = torch.tensor(geom, dtype=self.dtype).unsqueeze(0)
        
        if not self.return_img:
            tensor = rearrange(tensor, 'c h w -> (h w) c')
        
        return tensor


# ==================== DataLoader Factory ====================

def create_mechanism_dataloader(
    data_dir: Union[str, Path],
    batch_size: int = 32,
    shuffle: bool = True,
    num_workers: int = 4,
    pin_memory: bool = True,
    dataset_type: str = 'full',
    **dataset_kwargs,
) -> DataLoader:
    """
    Factory function to create mechanism dataset dataloader.
    
    Args:
        data_dir: Path to npz files
        batch_size: Batch size
        shuffle: Shuffle data
        num_workers: Number of data loading workers
        pin_memory: Pin memory for GPU transfer
        dataset_type: One of 'full', 'conditioned', 'geometry_only'
        **dataset_kwargs: Additional kwargs passed to dataset
    
    Returns:
        DataLoader instance
    """
    if dataset_type == 'full':
        dataset = MechanismDataset(data_dir, **dataset_kwargs)
    elif dataset_type == 'conditioned':
        dataset = MechanismConditionedDataset(data_dir, **dataset_kwargs)
    elif dataset_type == 'geometry_only':
        dataset = MechanismGeometryOnlyDataset(data_dir, **dataset_kwargs)
    else:
        raise ValueError(f"Unknown dataset_type: {dataset_type}")
    
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=pin_memory,
        drop_last=True,
    )


# ==================== Normalization Helper ====================

class DataNormalizer:
    """
    Normalizer for mechanism dataset.
    
    Computes statistics from dataset and provides normalize/unnormalize methods.
    """
    
    def __init__(self, dataset: MechanismDataset):
        """Compute normalization statistics from dataset."""
        print("[DataNormalizer] Computing statistics...")
        
        # Collect all data
        all_data = []
        for i in range(len(dataset)):
            all_data.append(dataset[i])
        all_data = torch.stack(all_data)  # (N, C, H, W) or (N, H*W, C)
        
        self.mean = all_data.mean(dim=0)
        self.std = all_data.std(dim=0)
        self.min = all_data.min(dim=0)[0]
        self.max = all_data.max(dim=0)[0]
        
        # Avoid division by zero
        self.std = torch.clamp(self.std, min=1e-6)
        
        print(f"  Mean range: [{self.mean.min():.4f}, {self.mean.max():.4f}]")
        print(f"  Std range: [{self.std.min():.4f}, {self.std.max():.4f}]")
    
    def normalize(self, x: torch.Tensor, method: str = 'minmax') -> torch.Tensor:
        """Normalize tensor."""
        if method == 'minmax':
            return (x - self.min) / (self.max - self.min + 1e-8)
        elif method == 'zscore':
            return (x - self.mean) / self.std
        else:
            raise ValueError(f"Unknown method: {method}")
    
    def unnormalize(self, x: torch.Tensor, method: str = 'minmax') -> torch.Tensor:
        """Unnormalize tensor."""
        if method == 'minmax':
            return x * (self.max - self.min) + self.min
        elif method == 'zscore':
            return x * self.std + self.mean
        else:
            raise ValueError(f"Unknown method: {method}")


